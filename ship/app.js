function matchOffering(input) {
  const normalized = input.trim().toLowerCase();
  if (!normalized) return offerings.braintap;
  return Object.values(offerings).find((offering) =>
    offering.aliases.some((alias) => normalized.includes(alias))
  ) || {
    ...offerings.braintap,
    name: "Prototype read",
    category: "Unseeded offering",
    verdict: "Needs manual audit",
    bigRead:
      "This static prototype does not yet run live research. It shows the OpenLabel loop using seeded examples while the audit engine remains manual.",
    honestProposition:
      "The useful next step is to run this offering through the manual audit workbook, then render the same soul, alternatives, reader panels, and evidence compression.",
    liveQuestion:
      "What is the offering asking the user to believe, and what evidence would make that belief proportionate?"
  };
}

function setText(id, text) {
  document.getElementById(id).textContent = text;
}

function setList(id, items) {
  const node = document.getElementById(id);
  node.innerHTML = "";
  items.forEach((item) => {
    const li = document.createElement("li");
    li.textContent = item;
    node.appendChild(li);
  });
}

function setCardGrid(id, items, className) {
  const node = document.getElementById(id);
  node.innerHTML = "";
  items.forEach(([title, body]) => {
    const article = document.createElement("article");
    article.className = className;
    const h3 = document.createElement("h3");
    h3.textContent = title;
    const p = document.createElement("p");
    p.textContent = body;
    article.append(h3, p);
    node.appendChild(article);
  });
}

function render(offering) {
  setText("product-name", offering.name);
  setText("product-category", offering.category);
  setText("verdict-pill", offering.verdict);
  setText("coverage-pill", offering.coverage);
  setText("big-read", offering.bigRead);
  setText("honest-proposition", offering.honestProposition);
  setText("live-question", offering.liveQuestion);

  setText("current-seed", offering.currentSoul.seed);
  setText("current-purpose", offering.currentSoul.purpose);
  setList("current-instructions", offering.currentSoul.instructions);
  setText("current-halfbaked", offering.currentSoul.halfBaked);
  setText("current-exchange", offering.currentSoul.exchange);

  setText("honest-purpose", offering.honestSoul.purpose);
  setList("honest-instructions", offering.honestSoul.instructions);
  setText("honest-exchange", offering.honestSoul.exchange);

  setCardGrid("alternatives", offering.alternatives, "alt-card");
  setText("scaffolds", offering.conviviality.scaffolds);
  setText("substitutes", offering.conviviality.substitutes);
  setText("best-use", offering.conviviality.bestUse);
  setCardGrid("reader-panels", offering.panels, "reader-card");

  setText("agent-flags", offering.agent.flags);
  setText("agent-survives", offering.agent.survives);
  setText("agent-remediation", offering.agent.remediation);
  setText("saw", offering.evidence.saw);
  setText("means", offering.evidence.means);
  setText("gaps", offering.evidence.gaps);
  setList("concerns", offering.evidence.concerns);

  document.querySelectorAll(".sample-button").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.target === keyForOffering(offering));
  });
}

function keyForOffering(offering) {
  return Object.entries(offerings).find(([, value]) => value.name === offering.name)?.[0] || "";
}

function runLookup() {
  const input = document.getElementById("lookup");
  const offering = matchOffering(input.value);
  render(offering);
  document.getElementById("read").scrollIntoView({ behavior: "smooth", block: "start" });
}

document.getElementById("lookup-button").addEventListener("click", runLookup);
document.getElementById("lookup").addEventListener("keydown", (event) => {
  if (event.key === "Enter") runLookup();
});

document.querySelectorAll(".sample-button").forEach((button) => {
  button.addEventListener("click", () => {
    const offering = offerings[button.dataset.target];
    document.getElementById("lookup").value = offering.aliases[0];
    render(offering);
    document.getElementById("read").scrollIntoView({ behavior: "smooth", block: "start" });
  });
});

render(offerings.braintap);
